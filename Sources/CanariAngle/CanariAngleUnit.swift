import Foundation

//--------------------------------------------------------------------------------------------------
// struct CanariAngleUnit
//--------------------------------------------------------------------------------------------------

public enum CanariAngleUnit : Comparable {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  case degree
  case grade
  case radian

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public func radian () -> Double {
    switch self {
      case .degree : return .pi / 180
      case .grade  : return .pi / 200.0
      case .radian : return 1.0
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var unitString : String {
    switch self {
      case .degree : return "°"
      case .grade  : return "gr"
      case .radian : return "rad"
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

