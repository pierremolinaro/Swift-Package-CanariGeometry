import Foundation

//--------------------------------------------------------------------------------------------------
// struct CanariAngleUnit
//--------------------------------------------------------------------------------------------------

public enum CanariAngleUnit : Comparable {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  case degree
  case radian
  case π

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var πValue : Double {
    switch self {
      case .degree : return 1.0 / 180.0
      case .π  : return 1.0
      case .radian : return 1.0 / .pi
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var unitString : String {
    switch self {
      case .degree : return "°"
      case .π  : return "* π"
      case .radian : return "rad"
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

